#!/usr/bin/env bash
#
# Creates a branch that brings an upstream release into the fork.
#
# Usage (from the plugin root, on a clean checkout of the base branch):
#   bash .fork/sync.sh <upstream-tag> [fork-revision]
#   bash .fork/sync.sh 3.0.13          # -> branch sync/upstream-3.0.13, version 3.0.13.1
#
# What it does:
# 1. Merges the upstream tag, so upstream history stays in the fork, but takes
#    upstream's tree wholesale (no conflicts, no hand-resolved files).
# 2. Puts back the fork-owned files (.fork/ and the fork-*.yml workflows).
# 3. Applies .fork/apply-overlay.php, which re-creates every fork change.
# 4. Refreshes composer.lock's content-hash and commits.
#
# Anything the fork changes in upstream files must therefore live in
# apply-overlay.php. A hand edit to an upstream file is overwritten by the
# next sync.
#
# Needs: git, php, composer, and an `upstream` remote (added if missing).

set -euo pipefail

# Paths the fork owns. They are kept from the current checkout across the reset.
FORK_PATHS=(
	.fork
	.github/workflows/fork-sync.yml
	.github/workflows/fork-ci.yml
	.github/workflows/fork-release.yml
)
UPSTREAM_URL="https://github.com/humanmade/S3-Uploads.git"

# Everything runs inside main(), so bash has read the whole script before
# the reset below deletes and restores this file.
main() {
	local tag="${1:?Usage: bash .fork/sync.sh <upstream-tag> [fork-revision]}"
	local version="${tag#v}.${2:-1}"
	local branch="sync/upstream-${tag}"

	cd "$(dirname "$0")/.."

	if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
		echo "Working tree has uncommitted changes; commit or stash them first." >&2
		exit 1
	fi

	git remote get-url upstream > /dev/null 2>&1 || git remote add upstream "$UPSTREAM_URL"
	git fetch --quiet --no-tags upstream "refs/tags/${tag}:refs/tags/${tag}"

	# Keep a copy of the fork-owned files from the current checkout.
	local keep
	keep="$(mktemp -d)"
	local start_ref
	start_ref="$(git rev-parse --abbrev-ref HEAD)"
	# shellcheck disable=SC2064 # Expand now: these are locals, gone when the trap fires.
	trap "status=\$?; rm -rf '$keep'; if [ \$status -ne 0 ]; then
		echo >&2
		echo 'Sync failed and left $branch half-done. To discard it:' >&2
		echo '  git reset --hard && git checkout $start_ref && git branch -D $branch' >&2
	fi" EXIT
	local path
	for path in "${FORK_PATHS[@]}"; do
		if [ -e "$path" ]; then
			mkdir -p "$keep/$(dirname "$path")"
			cp -R "$path" "$keep/$path"
		fi
	done

	git checkout --quiet -B "$branch"

	# Record the merge with upstream, then make the tree exactly upstream's.
	git merge --quiet --no-ff --no-commit -s ours "refs/tags/${tag}" \
		-m "Merge upstream ${tag}" > /dev/null
	git read-tree --reset -u "refs/tags/${tag}"

	for path in "${FORK_PATHS[@]}"; do
		if [ -e "$keep/$path" ]; then
			mkdir -p "$(dirname "$path")"
			rm -rf "$path"
			cp -R "$keep/$path" "$path"
		fi
	done

	php .fork/apply-overlay.php "$version"

	# The overlay edits composer.json's "extra", which is part of the lock hash.
	# This only refreshes the hash; locked package versions stay as upstream set them.
	composer update --lock --no-install --no-scripts --no-plugins --ignore-platform-reqs --quiet

	git add --all
	git commit --quiet --no-verify -m "Sync upstream ${tag} as ${version}

Upstream release: https://github.com/humanmade/S3-Uploads/releases/tag/${tag}
Generated by .fork/sync.sh."

	echo "Created ${branch} with version ${version}."
}

main "$@"
